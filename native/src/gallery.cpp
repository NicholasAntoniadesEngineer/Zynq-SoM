const std::string begin_marker = "<!-- schgen:gallery -->";
const std::string end_marker = "<!-- /schgen:gallery -->";
const std::string generated = "<!-- GENERATED by "
                              "`schgen gallery`"
                              " — edits between these markers are overwritten -->";
const std::vector<std::pair<std::string, std::string>> views{
    {"3d_persp", "Perspective (front)"},
    {"3d_persp_rear", "Perspective (rear)"},
    {"3d_top", "Top"},
    {"3d_bottom", "Bottom"},
    {"3d_front", "Front edge"},
    {"3d_back", "Back edge"},
    {"3d_left", "Left edge"},
    {"3d_right", "Right edge"}};
bool contained(const fs::path &rel) {
    return !rel.empty() && (rel.begin() == rel.end() || *rel.begin() != "..");
}
std::string project_rel(const GalleryInput &in) {
    auto p = document_detail::absolute(in.project_root);
    auto rel = p.lexically_relative(document_detail::absolute(in.repository_root));
    return contained(rel) ? rel.generic_string() : p.filename().string();
}
std::string relative(const GalleryInput &in, const fs::path &dir, const std::string &target) {
    return (document_detail::absolute(in.repository_root) / target)
        .lexically_normal()
        .lexically_relative(document_detail::absolute(dir))
        .generic_string();
}
std::string image(const std::string &url, const std::string &name, int width) {
    return "[<img src=\"" + url + "\" width=\"" + std::to_string(width) + "\" alt=\"" + name +
           "\">](" + url + ")<br>**" + name + "**";
}
std::vector<std::string> grid(const std::vector<std::string> &cells, std::size_t cols) {
    std::vector<std::string> out{"| " + join(std::vector<std::string>(cols, " "), " | ") + " |"};
    std::string line = "|";
    for (std::size_t i = 0; i < cols; ++i)
        line += "---|";
    out.push_back(line);
    for (std::size_t i = 0; i < cells.size(); i += cols) {
        std::vector<std::string> row(cols, " ");
        for (std::size_t j = 0; j < cols && i + j < cells.size(); ++j)
            row[j] = cells[i + j];
        out.push_back("| " + join(row, " | ") + " |");
    }
    return out;
}
void append(std::vector<std::string> &out, const std::vector<std::string> &lines) {
    out.insert(out.end(), lines.begin(), lines.end());
}
std::vector<GallerySheet> sorted_sheets(const GalleryInput &in) {
    auto rows = in.sheets;
    std::stable_sort(rows.begin(), rows.end(), [](const auto &a, const auto &b) {
        return std::tie(a.name, a.title) < std::tie(b.name, b.title);
    });
    return rows;
}
bool duplicate(const std::string &stem) {
    auto cp = codepoints(stem);
    if (!cp.empty() && cp.back() == '\n')
        cp.pop_back(); // Python regex '$'
    std::size_t i = cp.size();
    while (i && bringup_detail::decimal_digit(cp[i - 1]) >= 0)
        --i;
    return i < cp.size() && i && cp[i - 1] == ' ';
}
std::vector<std::string> ratsnest_stems(const GalleryInput &in) {
    std::vector<std::string> out;
    for (const auto &name : in.ratsnest_files) {
        fs::path p(name);
        if (p.extension() != ".png" && name != ".png")
            continue;
        const auto stem = p.stem().string();
        if (stem != "som" && !duplicate(stem))
            out.push_back(stem);
    }
    std::sort(out.begin(), out.end());
    return out;
}
bool has(const GalleryInput &in, const std::string &stem) {
    return in.render_files.count(stem + ".png") != 0;
}
std::vector<std::string> view_lines(const GalleryInput &in, const fs::path &dir) {
    std::vector<std::string> out{"## Generated 3D board views", ""}, cells;
    for (const auto &[stem, label] : views)
        if (has(in, stem))
            cells.push_back(image(relative(in, dir, project_rel(in) + "/renders/" + stem + ".png"),
                                  label, 200));
    if (cells.empty()) {
        append(out, {"*(3D board renders pending — run "
                     "`schgen board`"
                     ".)*",
                     ""});
        return out;
    }
    out.push_back("The placed board rendered from " + std::to_string(cells.size()) +
                  " angles by "
                  "`schgen board`"
                  " (kicad-cli, the real component 3D models) — "
                  "regenerated and committed every build, just like the sheets below.");
    out.push_back("");
    append(out, grid(cells, 4));
    out.push_back("");
    return out;
}
std::vector<std::string> ratsnest_lines(const GalleryInput &in, const fs::path &dir) {
    std::vector<std::string> out{"## Ratsnest views", ""}, cells;
    const auto prefix = project_rel(in) + "/renders/";
    for (const auto &[stem, label] : std::vector<std::pair<std::string, std::string>>{
             {"ratsnest_top", "Board (top)"}, {"ratsnest_bottom", "Board (bottom)"}})
        if (has(in, stem))
            cells.push_back(image(relative(in, dir, prefix + stem + ".png"), label, 420));
    if (std::find(in.ratsnest_files.begin(), in.ratsnest_files.end(), "som.png") !=
        in.ratsnest_files.end())
        cells.push_back(image(relative(in, dir, prefix + "ratsnest/som.png"), "SoM region", 420));
    const auto sheets = ratsnest_stems(in);
    if (cells.empty() && sheets.empty()) {
        append(out, {"*(ratsnest renders pending — run "
                     "`schgen board`"
                     ".)*",
                     ""});
        return out;
    }
    append(out, {"Placed-board airwires, regenerated by "
                 "`schgen board`"
                 ": "
                 "blue/orange = the subsystem's parts (top/bottom side), steel = SoM, green = "
                 "intra-subsystem, red = to the SoM. "
                 "`wired`"
                 " = in "
                 "`placement.wired_sheets`"
                 ".",
                 ""});
    if (!cells.empty()) {
        append(out, grid(cells, 2));
        out.push_back("");
    }
    cells.clear();
    for (const auto &name : sheets)
        cells.push_back(image(relative(in, dir, prefix + "ratsnest/" + name + ".png"), name, 200) +
                        (in.wired_sheets.count(name) ? " "
                                                       "`wired`"
                                                     : ""));
    if (!cells.empty()) {
        append(out, grid(cells, 4));
        out.push_back("");
    }
    return out;
}
std::string universal_newlines(const std::string &raw) {
    (void)codepoints(raw);
    std::string text;
    for (std::size_t i = 0; i < raw.size(); ++i) {
        if (raw[i] != '\r') {
            text += raw[i];
            continue;
        }
        text += '\n';
        if (i + 1 < raw.size() && raw[i + 1] == '\n')
            ++i;
    }
    return text;
}

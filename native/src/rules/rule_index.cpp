#include "schgen/rules.hpp"

#include <iostream>
#include <sstream>

namespace schgen::rules {

const char* enforcement_name(Enforcement enforcement) {
    switch (enforcement) {
    case Enforcement::gate: return "GATE";
    case Enforcement::measured: return "MEASURED";
    }
    return "MEASURED";
}

std::string rule_book_markdown() {
    std::ostringstream text;
    text << "# Placement rule book\n\n"
         << "Generated by `schgen rules` from `native/src/rules`. Do not edit by hand; a contract test compares this file with the generated text.\n\n"
         << "Each rule is one file, `native/src/rules/<area>/<id with underscores>.cpp`, holding the rule, its thresholds and its one check. "
         << "The order is fixed in `native/src/rules/rule_book.cpp`. The final placement gate runs every rule on the placed board: "
         << "a GATE rule with findings fails the board, a MEASURED rule reports its findings without failing it. "
         << "\"Met by\" names the stage that must satisfy the rule: the starting placement, or the layout stage that seats, arranges and squeezes it.\n\n"
         << "| id | area | enforcement | met by | statement | why | source | confidence |\n"
         << "|---|---|---|---|---|---|---|---|\n";
    for (const auto& entry : rule_book())
        text << "| " << entry.rule.id << " | " << entry.rule.area << " | " << enforcement_name(entry.rule.enforcement)
             << " | " << (entry.rule.met_by == Stage::placement ? "starting placement" : "layout stage") << " | "
             << entry.rule.statement << " | " << entry.rule.why << " | " << entry.rule.source << " | "
             << entry.rule.confidence << " |\n";
    return text.str();
}

std::optional<int> run_rules_command(int argc, char** argv) {
    if (argc < 2 || std::string_view(argv[1]) != "rules") return std::nullopt;
    if (argc != 2) {
        std::cerr << "usage: schgen rules\n  prints the placement rule book as markdown\n";
        return 2;
    }
    std::cout << rule_book_markdown();
    return 0;
}

}

const JsonNode& field(const JsonNode& n,const std::string& name,JsonKind kind) {
    const auto p=object_field(n,name);if(!p||p->kind!=kind)throw ProjectError("manufacturing metadata: invalid "+name);return *p;
}
std::string text(const JsonNode& n,const std::string& key) {return field(n,key,JsonKind::String).string_value;}
long long count(const JsonNode& n) {
    if(n.kind==JsonKind::Bool)return n.bool_value?1:0;
    if(n.kind==JsonKind::Number){if(!std::isfinite(n.number_value)||n.number_value< -9223372036854775808.0||n.number_value>=9223372036854775808.0)throw ProjectError("fallback count out of range");return static_cast<long long>(n.number_value);}
    if(n.kind==JsonKind::String){const auto s=verification::strip(n.string_value);std::size_t used=0;const auto value=std::stoll(s,&used);if(used!=s.size())throw ProjectError("invalid fallback count");return value;}
    throw ProjectError("invalid fallback count");
}
ManufacturingCounts counts(const JsonNode& n) {
    if(n.kind!=JsonKind::Object)throw ProjectError("fallback counts must be an object");ManufacturingCounts out;for(const auto& [k,v]:n.object_value)out[k]=count(v);return out;
}
std::optional<ManufacturingCounts> load_counts(const std::filesystem::path& path) {
    try {auto n=parse_json_file(path.string());return counts(field(n,"counts",JsonKind::Object));}
    catch(const std::bad_alloc&){throw;}catch(const std::exception&){return std::nullopt;}
}
void write_counts(const std::filesystem::path& path,const ManufacturingCounts& counts) {
    std::string text="{\n \"counts\": {";bool first=true;
    for(const auto& [name,n]:counts){text+=first?"\n":",\n";first=false;text+="  "+quote(name)+": "+std::to_string(n);}
    if(!counts.empty())text+="\n ";text+="},\n \"note\": \"fallback ratchet ceilings — a build whose count EXCEEDS its ceiling FAILS; ceilings only ever DECREASE (pinned from a measured build, reviewed in git). A name absent here is allowed zero firings.\"\n}\n";
    // Python json.dumps defaults to ASCII escaping.
    auto at=text.find("—");if(at!=text.npos)text.replace(at,std::string("—").size(),"\\u2014");
    write_atomic_file(path.string(),{text.begin(),text.end()});
}

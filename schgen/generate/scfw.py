def _ascii(text: str) -> str:
    # pure-ASCII for embedded toolchains (mirrors firmware.py/devicetree.py)
    return text.replace("—", "--").replace("→", "->")


def generate(out_dir: Path = DEFAULT_OUT) -> list[Path]:
    """Build + write the whole SC firmware scaffold into ``out_dir``.  Returns
    the written paths in deterministic emit order."""
    m = Model()
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    names = [n for n, _ in _FILES]
    for name, fn in _FILES:
        path = out_dir / name
        path.write_text(_ascii(fn(m)))
        written.append(path)
    readme = out_dir / "README.md"
    readme.write_text(_ascii(gen_readme(m, names)))
    written.append(readme)
    return written


def cmd_scfw(args: argparse.Namespace) -> int:
    out_dir = args.output or DEFAULT_OUT
    written = generate(out_dir)
    print(f"SCFW SCAFFOLD: {out_dir} ({len(written)} files)")
    for p in written:
        print(f"  {p.name}")
    return 0
